def opt(entry):
    kind = entry[0]
    if kind == "title":
        return {"text": f"CHIM Vampire Bridge {VERSION} by SaurOff", "type": "header"}
    if kind == "header":
        return {"text": "$COV_" + entry[1], "type": "header"}
    _, oid, key = entry[:3]
    e = {"id": oid, "text": "$COV_" + key, "type": "slider" if kind == "fslider" else kind, "help": "$COV_" + key + "H"}
    if kind == "toggle":
        e["valueOptions"] = {"sourceType": "ModSettingBool"}
    elif kind == "input":
        e["valueOptions"] = {"sourceType": "ModSettingString"}
    else:
        lo, hi, step, fmt = entry[3:]
        e["valueOptions"] = {"min": lo, "max": hi, "step": step, "formatString": fmt,
                             "sourceType": "ModSettingFloat" if kind == "fslider" else "ModSettingInt"}
    return e


